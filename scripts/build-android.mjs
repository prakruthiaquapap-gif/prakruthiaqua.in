import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const bundle=process.argv.includes("--aab");
const signed=!!process.env.ANDROID_KEYSTORE_PATH;
const releaseApk=!bundle&&process.argv.includes("--release");
if(releaseApk&&!signed) throw new Error("Release APK requires the upload signing environment variables.");
const localJava=path.join(root,'.android-toolchain/java/Contents/Home');
const localSdk=path.join(root,'.android-toolchain/sdk');
const env={...process.env};
if(!env.JAVA_HOME&&fs.existsSync(localJava))env.JAVA_HOME=localJava;
if(!env.ANDROID_HOME&&fs.existsSync(localSdk))env.ANDROID_HOME=localSdk;
if(!env.GRADLE_USER_HOME)env.GRADLE_USER_HOME=path.join(root,'.android-gradle');
if(!env.ANDROID_USER_HOME)env.ANDROID_USER_HOME=path.join(root,'.android-toolchain/android-user-home');
fs.mkdirSync(env.ANDROID_USER_HOME,{recursive:true});
function run(command,args,cwd=root){const r=spawnSync(command,args,{cwd,env,stdio:'inherit'});if(r.error)throw r.error;if(r.status!==0)process.exit(r.status||1)}
run('node',['scripts/android-assets.mjs']);
run('npx',['cap','sync','android']);
run('./gradlew',[bundle?'bundleRelease':releaseApk?'assembleRelease':'assembleDebug','--no-daemon'],path.join(root,'android'));
fs.mkdirSync('output/android',{recursive:true});
const source=bundle?'android/app/build/outputs/bundle/release/app-release.aab':releaseApk?'android/app/build/outputs/apk/release/app-release.apk':'android/app/build/outputs/apk/debug/app-debug.apk';
const destination=bundle?`output/android/Prakruthi-Aqua-release${signed?'':'-unsigned'}.aab`:releaseApk?'output/android/Prakruthi-Aqua-release.apk':'output/android/Prakruthi-Aqua-debug.apk';
fs.copyFileSync(source,destination);
console.log((bundle?'AAB':'APK')+': '+path.join(root,destination));
if(bundle&&!signed) console.log('Unsigned release bundle: an upload signing key is required before Play Console upload.');
